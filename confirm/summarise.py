"""What a second scoring function (Rosetta ref2015 interface energy) says about the docked poses.

Pure logic over the input manifest and the Rosetta scores, plus a CLI. Reads PyRosetta's output files only; it does not
import PyRosetta, so it runs in the sidacore env.
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

from scipy.stats import spearmanr

NEAR_NATIVE = 2.0       # the same acceptance as Step 4


def _rank(value, ordered):
    return 1 + sum(1 for v in ordered if v < value)


def _view(rows: list, values: dict, crystal_pose: str, min_rmsd: dict | None, excluded: set) -> dict:
    """One scoring view of one engine's poses. `excluded` poses (no contact with the receptor) never enter the Rosetta ranking."""
    scores = [values[r["pose"]] for r in rows]
    ranked = sorted((r for r in rows if r["pose"] not in excluded), key=lambda r: values[r["pose"]])
    best = min(rows, key=lambda r: r["rmsd_to_crystal"])
    top = ranked[0]
    kept = [r for r in rows if r["pose"] not in excluded]
    sp = spearmanr([r["score"] for r in kept], [values[r["pose"]] for r in kept]).statistic if len(kept) > 2 else None
    return {"engine_top1_rmsd": rows[0]["rmsd_to_crystal"], "engine_top1_value": scores[0],
            "rosetta_top1_pose": top["pose"], "rosetta_top1_rank_in_engine": top["rank"],
            "rosetta_top1_rmsd": top["rmsd_to_crystal"], "rosetta_top1_value": values[top["pose"]],
            "rosetta_top1_min_rmsd": (min_rmsd or {}).get(top["pose"]),
            "best_rmsd": best["rmsd_to_crystal"],
            "best_rmsd_pose_rosetta_rank": ranked.index(best) + 1 if best in ranked else None,
            "crystal_value": values[crystal_pose], "crystal_better_than_engine_top1": bool(values[crystal_pose] < scores[0]),
            "engine_top1_minus_crystal": scores[0] - values[crystal_pose],
            "crystal_rank_among_all": _rank(values[crystal_pose], [values[r["pose"]] for r in kept]),
            "spearman_score_vs_value": None if sp is None or sp != sp else float(sp)}


def summarise_job(manifest: list, dG: dict, min_rmsd: dict | None = None, contact: dict | None = None,
                  total: dict | None = None) -> dict:
    """{engine: summary}. `dG`: pose -> dG_separated (lower is better; the registered measure). `contact`: pose -> interface
    residues; a pose with none is excluded from the Rosetta ranking. `total`: pose -> minimised complex energy, an extra view
    added after the dG results were seen. KeyError if a pose has no score."""
    crystal = next(r for r in manifest if r["engine"] == "crystal")["pose"]
    out = {}
    for eng in sorted({r["engine"] for r in manifest} - {"crystal"}):
        rows = sorted((r for r in manifest if r["engine"] == eng), key=lambda r: r["rank"])
        for r in rows:
            dG[r["pose"]]                                          # KeyError for a pose that was never scored
        excl = {r["pose"] for r in rows if contact is not None and contact[r["pose"]] == 0}
        d = _view(rows, dG, crystal, min_rmsd, excl)
        out[eng] = {"n_poses": len(rows), "n_near_native": sum(r["rmsd_to_crystal"] <= NEAR_NATIVE for r in rows),
                    "n_no_contact": len(excl), **d,
                    "engine_top1_dG": d["engine_top1_value"], "crystal_dG": d["crystal_value"],
                    "spearman_score_vs_dG": d["spearman_score_vs_value"]}
        if total is not None:
            out[eng]["total"] = _view(rows, total, crystal, min_rmsd, excl)
    return out


def render_markdown(summaries: dict, notes: str = "") -> str:
    L = ["# Step 4 - Rosetta rescoring of the redocked poses", "",
         "Generated by `confirm/summarise.py`; numbers only. PyRosetta is free for academic use and needs a licence for "
         "commercial use; it is not part of `sidacore`.", "",
         "- Scoring function: Rosetta `ref2015`. Protocol (fixed before any docked pose was scored, identical for the "
         "deposited pose and every docked pose): Rosetta adds hydrogens; minimise the ligand's rigid-body jump and torsions and "
         "the side chains within 8 A of it (backbone and cofactors fixed); then InterfaceAnalyzer, ligand against everything "
         "else, partners separated and repacked. The number used is **dG_separated** (REU, lower is better).",
         "- Poses: every mode of seed 1 of each engine, plus the deposited ligand. This is a second, independent scoring "
         "function, not ground truth.", "",
         "| receptor | engine | engine top-1 RMSD (A) | Rosetta top-1 RMSD (A), as docked / after minimisation [its engine rank] | best RMSD in the list (A) [its Rosetta rank] "
         "| crystal dG | engine top-1 dG | crystal better than engine top-1 | Spearman, engine score vs dG |",
         "|---|---|---|---|---|---|---|---|---|"]
    for job, per in summaries.items():
        for eng, s in per.items():
            sp = "-" if s["spearman_score_vs_dG"] is None else "%.2f" % s["spearman_score_vs_dG"]
            if s["n_no_contact"]:
                sp += " (%d no-contact excluded)" % s["n_no_contact"]
            mn = "-" if s.get("rosetta_top1_min_rmsd") is None else "%.2f" % s["rosetta_top1_min_rmsd"]
            br = "-" if s["best_rmsd_pose_rosetta_rank"] is None else "%d" % s["best_rmsd_pose_rosetta_rank"]
            L.append("| %s | %s | %.2f | %.2f / %s [%d] | %.2f [%s] | %.1f | %.1f | %s | %s |" % (
                job, eng, s["engine_top1_rmsd"], s["rosetta_top1_rmsd"], mn, s["rosetta_top1_rank_in_engine"], s["best_rmsd"],
                br, s["crystal_dG"], s["engine_top1_dG"],
                "yes" if s["crystal_better_than_engine_top1"] else "**no**", sp))
    if any("total" in s for per in summaries.values() for s in per.values()):
        L += ["", "## Added after seeing the dG results: total complex energy", "",
              "dG_separated cannot tell a pose with no interface (dG = 0) from a weakly bound one, and for a charged ligand it is "
              "positive for most in-site poses. The minimised complex's total ref2015 energy is the same system in different "
              "ligand states, so differences between poses are directly comparable. This view was **not** in the protocol "
              "written beforehand.", "",
              "| receptor | engine | engine top-1 minus crystal (REU) | crystal lower than engine top-1 | Rosetta top-1 RMSD (A) [its engine rank] | Spearman |",
              "|---|---|---|---|---|---|"]
        for job, per in summaries.items():
            for eng, s in per.items():
                t = s.get("total")
                if t:
                    sp = "-" if t["spearman_score_vs_value"] is None else "%.2f" % t["spearman_score_vs_value"]
                    L.append("| %s | %s | %+.1f | %s | %.2f [%d] | %s |" % (job, eng, t["engine_top1_minus_crystal"],
                             "yes" if t["crystal_better_than_engine_top1"] else "**no**", t["rosetta_top1_rmsd"],
                             t["rosetta_top1_rank_in_engine"], sp))
    if notes.strip():
        L += ["", "## Notes", "", notes.strip()]
    return "\n".join(L) + "\n"


def main(argv=None) -> int:
    import argparse
    import sys
    from rdkit import Chem
    from sidacore.config import load_config
    from sidacore.redock import crystal_reference, ligand_template, pose_rmsd
    ap = argparse.ArgumentParser(description="Summarise the Rosetta rescoring.")
    ap.add_argument("--config", required=True)
    ap.add_argument("--prepared", required=True)
    ap.add_argument("--inputs", required=True, help="rosetta_in directory (manifest.csv)")
    ap.add_argument("--scores", required=True, help="rosetta_out directory (<job>.csv and <job>/<pose>.min.pdb)")
    ap.add_argument("--json")
    ap.add_argument("--report")
    ap.add_argument("--notes")
    a = ap.parse_args(argv)
    cfg = load_config(a.config)
    template = ligand_template(cfg.ligand_resname)
    man = list(csv.DictReader(open(Path(a.inputs) / "manifest.csv")))
    for r in man:
        r["rank"], r["rmsd_to_crystal"] = int(r["rank"]), float(r["rmsd_to_crystal"])
        r["score"] = float(r["score"]) if r["score"] != "" else None
    summaries = {}
    for job in sorted({r["job"] for r in man}):
        rr = list(csv.DictReader(open(Path(a.scores) / (job + ".csv"))))
        dG = {x["pose"]: float(x["dG_separated"]) for x in rr}
        contact = {x["pose"]: int(x["n_interface_residues"]) for x in rr}
        total = {x["pose"]: float(x["score_min"]) for x in rr}
        ref = crystal_reference(Path(a.prepared) / job / "ligand_crystal.pdb", template)
        minr = {}
        for pose in dG:
            f = Path(a.scores) / job / (pose + ".min.pdb")
            if f.exists():
                m = Chem.MolFromPDBFile(str(f), removeHs=False, sanitize=False, proximityBonding=True)
                minr[pose] = pose_rmsd(Chem.RemoveHs(m, sanitize=False), ref)
        summaries[job] = summarise_job([r for r in man if r["job"] == job], dG, minr, contact, total)
    if a.json:
        Path(a.json).write_text(json.dumps(summaries, indent=1))
    if a.report:
        Path(a.report).write_text(render_markdown(summaries, Path(a.notes).read_text() if a.notes and Path(a.notes).exists() else ""))
    for job, per in summaries.items():
        for eng, s in per.items():
            print("%-18s %-8s engine top-1 %.2f A | Rosetta top-1 %.2f A (engine rank %d) | crystal better: %s" % (
                job, eng, s["engine_top1_rmsd"], s["rosetta_top1_rmsd"], s["rosetta_top1_rank_in_engine"], s["crystal_better_than_engine_top1"]))
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(main())
