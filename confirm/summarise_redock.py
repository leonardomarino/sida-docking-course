"""The Step 4 registered rule applied to the RosettaLigand decoys, plus the native-start comparison.

Registered before any decoy was run: per seed, the top-1 decoy is the one with the lowest total score; PASS if the median over
seeds of its symmetry-corrected RMSD to the deposited pose is <= the acceptance (2 A). Ranking by interface delta is reported
beside it, not instead. Runs in the sidacore env; reads PyRosetta's output files only (no PyRosetta import).
"""
from __future__ import annotations

import csv
import json
import math
from pathlib import Path

from sidacore.redock import MIN_SEEDS, evaluate_seeds


def _valid(rows):
    return [r for r in rows if not r["error"] and math.isfinite(r["total_score"])]


def _per_seed(rows, rmsd, key):
    out = []
    for seed in sorted({r["seed"] for r in rows}):
        ok = sorted((r for r in _valid(rows) if r["seed"] == seed), key=lambda r: r[key])
        if not ok:
            raise ValueError("every decoy of seed %d failed; the seed cannot be ranked" % seed)
        out.append({"seed": seed, "top1_rmsd": rmsd[ok[0]["decoy"]], "top1_score": ok[0][key],
                    "best_top5_rmsd": min(rmsd[r["decoy"]] for r in ok[:5]), "n_poses": len(ok)})
    return out


def summarise_job(dock_rows: list, native_rows: list, rmsd: dict, accept: float) -> dict:
    ok = _valid(dock_rows)
    allr = sorted(ok, key=lambda r: r["total_score"])
    best = min(ok, key=lambda r: rmsd[r["decoy"]])
    nat = _valid(native_rows)
    out = {"n_decoys": len(dock_rows), "n_failed": len(dock_rows) - len(ok),
           "by_total_score": evaluate_seeds(_per_seed(dock_rows, rmsd, "total_score"), accept, min_seeds=MIN_SEEDS),
           "by_interface_delta": evaluate_seeds(_per_seed(dock_rows, rmsd, "interface_delta"), accept, min_seeds=MIN_SEEDS),
           "near_native_fraction": sum(rmsd[r["decoy"]] <= accept for r in ok) / len(ok),
           "best_decoy_rmsd": rmsd[best["decoy"]], "best_decoy_rank_by_score": allr.index(best) + 1, "native": None}
    if nat:
        nb, db = min(r["total_score"] for r in nat), min(r["total_score"] for r in ok)
        out["native"] = {"n": len(nat), "n_failed": len(native_rows) - len(nat), "best_total_score": nb,
                         "best_interface_delta": min(r["interface_delta"] for r in nat),
                         "lower_than_best_docked_total": bool(nb < db), "margin_to_best_docked": db - nb,
                         "median_rmsd_to_crystal": sorted(rmsd[r["decoy"]] for r in nat if r["decoy"] in rmsd)[len(nat) // 2]
                         if all(r["decoy"] in rmsd for r in nat) else None}
    return out


def render_markdown(summaries: dict, notes: str = "") -> str:
    L = ["# Step 4 - RosettaLigand redock", "",
         "Generated by `confirm/summarise_redock.py`; numbers only. PyRosetta is free for academic use and needs a licence for "
         "commercial use; it is not part of `sidacore`.", "",
         "- Protocol (fixed before any decoy was run): the apo receptor is relaxed with FastRelax restrained to the crystal "
         "coordinates; per seed, an RDKit start conformer centred on the C4X box (never the crystal pose) goes through Transform, "
         "HighResDocker and FinalMinimizer; interface energy is evaluated without the coordinate-constraint term.",
         "- Registered rule: per seed the top-1 decoy is the one with the **lowest total score**; **PASS** if the median over seeds "
         "of its symmetry-corrected RMSD to the deposited pose is <= 2 A. Ranking by interface delta is reported beside it, not instead.",
         "- 'Native start' refines the deposited pose with the same HighResDocker/FinalMinimizer steps (no Transform): its score "
         "against the best docked decoy separates a search failure (native scores better, docking did not find it) from a scoring "
         "failure (a wrong decoy scores at least as well).", "",
         "| receptor | top-1 RMSD median, by total score (within 2 A) | verdict | top-1 median, by interface delta (within) | near-native decoys | "
         "best decoy RMSD [its score rank] | native-start best total vs best docked | failed |",
         "|---|---|---|---|---|---|---|---|"]
    for job, s in summaries.items():
        t, i, n = s["by_total_score"], s["by_interface_delta"], s["native"]
        nat = "-" if not n else "%.1f vs %.1f (%s by %.1f)" % (n["best_total_score"], n["best_total_score"] + n["margin_to_best_docked"],
                                                           "native lower" if n["lower_than_best_docked_total"] else "docked lower or equal",
                                                           abs(n["margin_to_best_docked"]))
        L.append("| %s | %.2f (%d/%d) | %s | %.2f (%d/%d) | %.0f%% | %.2f [%d] | %s | %d |" % (
            job, t["top1_median"], t["top1_n_within"], t["n_seeds"], "**PASS**" if t["passes"] else "**FAIL**",
            i["top1_median"], i["top1_n_within"], i["n_seeds"], 100 * s["near_native_fraction"], s["best_decoy_rmsd"],
            s["best_decoy_rank_by_score"], nat, s["n_failed"] + (s["native"]["n_failed"] if s["native"] else 0)))
    if notes.strip():
        L += ["", "## Notes", "", notes.strip()]
    return "\n".join(L) + "\n"


def _read(path):
    rows = list(csv.DictReader(open(path)))
    for r in rows:
        for k in ("seed", "index"):
            r[k] = int(r[k])
        for k in ("total_score", "interface_delta"):
            r[k] = float(r[k])
    return rows


def main(argv=None) -> int:
    import argparse
    import sys
    from rdkit import Chem
    from sidacore.config import load_config
    from sidacore.redock import crystal_reference, ligand_template, pose_rmsd
    ap = argparse.ArgumentParser(description="Summarise the RosettaLigand redock.")
    ap.add_argument("--config", required=True)
    ap.add_argument("--prepared", required=True)
    ap.add_argument("--decoys", required=True, help="rosetta_dock directory (<job>/dock.csv, native.csv, dock/*.pdb)")
    ap.add_argument("--json")
    ap.add_argument("--report")
    ap.add_argument("--notes")
    a = ap.parse_args(argv)
    cfg = load_config(a.config)
    template = ligand_template(cfg.ligand_resname)
    out = {}
    for jd in sorted(p for p in Path(a.decoys).iterdir() if (p / "dock.csv").exists()):
        ref = crystal_reference(Path(a.prepared) / jd.name / "ligand_crystal.pdb", template)
        dock, native = _read(jd / "dock.csv"), (_read(jd / "native.csv") if (jd / "native.csv").exists() else [])
        rmsd = {}
        for r in dock + native:
            f = jd / ("native" if r["decoy"].startswith("native") else "dock") / (r["decoy"] + ".pdb")
            if not r["error"] and f.exists():
                m = Chem.MolFromPDBFile(str(f), removeHs=False, sanitize=False, proximityBonding=True)
                rmsd[r["decoy"]] = pose_rmsd(Chem.RemoveHs(m, sanitize=False), ref)
        out[jd.name] = summarise_job(dock, native, rmsd, cfg.redock_rmsd_acceptance)
    if a.json:
        Path(a.json).write_text(json.dumps(out, indent=1))
    if a.report:
        Path(a.report).write_text(render_markdown(out, Path(a.notes).read_text() if a.notes and Path(a.notes).exists() else ""))
    for job, s in out.items():
        t = s["by_total_score"]
        print("%-18s top-1 median %.2f A (%d/%d within) %s | by interface %.2f | near-native decoys %.0f%% | native lower: %s" % (
            job, t["top1_median"], t["top1_n_within"], t["n_seeds"], "PASS" if t["passes"] else "FAIL",
            s["by_interface_delta"]["top1_median"], 100 * s["near_native_fraction"],
            s["native"]["lower_than_best_docked_total"] if s["native"] else "n/a"))
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(main())
