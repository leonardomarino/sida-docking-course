"""Which polar contacts of the deposited ligand does a docked pose keep?

Built on biotite's cell list. Contacts are scored per receptor RESIDUE, not per ligand atom label: the two carboxylate oxygens of ornithine are
interchangeable, so an atom-by-atom comparison would call a correct pose wrong. Descriptive only: the cutoff is a convention, not a fitted value.
"""
import csv
from collections import namedtuple
from pathlib import Path

import biotite.structure as struc
import biotite.structure.io.pdb as pdb
import numpy as np

CUTOFF = 3.5                                  # A, heavy N/O pairs
CARBOXYLATE = ("O", "OXT")
Contact = namedtuple("Contact", "res_name chain res_id rec_atom lig_atom distance")


def _heavy_polar(atoms):
    return atoms[np.isin(atoms.element, ["N", "O"])]


def polar_contacts(receptor, ligand, cutoff: float = CUTOFF) -> list:
    """Every receptor N/O to ligand N/O pair within `cutoff` (hydrogens and carbons never count)."""
    rec, lig = _heavy_polar(receptor), _heavy_polar(ligand)
    cells = struc.CellList(rec, cutoff)
    out = []
    for atom in lig:
        for j in cells.get_atoms(atom.coord, cutoff):
            d = float(struc.distance(atom, rec[j]))
            if d <= cutoff:
                out.append(Contact(str(rec.res_name[j]), str(rec.chain_id[j]), int(rec.res_id[j]), str(rec.atom_name[j]), str(atom.atom_name), d))
    return out


def contact_residues(contacts) -> set:
    return {(c.res_name, c.chain, c.res_id) for c in contacts}


def protein_only(residues: set) -> set:
    """Drop cofactor and ligand residues (FAD, NADP, ...): they are held by the receptor model, not by the protein."""
    aa = set(struc.info.amino_acid_names())
    return {r for r in residues if r[0] in aa}


def retention(native: set, pose: set):
    """(kept, lost) native contact residues. A new contact elsewhere does not make up for a lost one."""
    return native & pose, native - pose


def min_distance(receptor, ligand, res_id: int, rec_atom: str, lig_atoms) -> float:
    rec_sel = receptor[(receptor.res_id == res_id) & (receptor.atom_name == rec_atom)]
    lig_sel = ligand[np.isin(ligand.atom_name, list(lig_atoms))]
    if len(rec_sel) == 0 or len(lig_sel) == 0:
        raise ValueError("no atom %s of residue %d (receptor) or none of %s (ligand)" % (rec_atom, res_id, list(lig_atoms)))
    return float(min(struc.distance(r, l) for r in rec_sel for l in lig_sel))


def read_job(job_dir, pose: str):
    """(receptor, ligand) AtomArrays for one pose of one Rosetta-input job directory."""
    job_dir = Path(job_dir)
    rec = pdb.PDBFile.read(str(job_dir / "receptor.pdb")).get_structure(model=1)
    lig = pdb.PDBFile.read(str(job_dir / "poses" / (pose + ".pdb"))).get_structure(model=1)
    return rec, lig


# ---------------------------------------------------------------------------------------------- the report
def analyse_job(job_dir, manifest_rows: list) -> dict:
    """Per engine: contact retention of the top-ranked pose, of the closest-to-crystal pose, and of the best-ranked pose that keeps every native contact."""
    job_dir = Path(job_dir)
    rec, crystal = read_job(job_dir, "crystal")
    native = contact_residues(polar_contacts(rec, crystal))
    summary = {"native": sorted(native, key=lambda r: r[2]), "lys107_crystal": min_distance(rec, crystal, 107, "NZ", CARBOXYLATE), "engines": {}}
    for engine in sorted({r["engine"] for r in manifest_rows if r["engine"] != "crystal"}):
        rows = sorted((r for r in manifest_rows if r["engine"] == engine), key=lambda r: int(r["rank"]))
        poses = []
        for r in rows:
            _, lig = read_job(job_dir, r["pose"])
            kept, lost = retention(native, contact_residues(polar_contacts(rec, lig)))
            poses.append({"rank": int(r["rank"]), "rmsd": float(r["rmsd_to_crystal"]), "kept": len(kept), "lost": sorted(x[2] for x in lost),
                          "lys107": min_distance(rec, lig, 107, "NZ", CARBOXYLATE)})
        nonprotein = {r[2] for r in native - protein_only(native)}
        full = [p for p in poses if not (set(p["lost"]) - nonprotein)]       # every PROTEIN contact kept; a cofactor contact may be lost
        summary["engines"][engine] = {"n_poses": len(poses), "top1": poses[0], "closest": min(poses, key=lambda p: p["rmsd"]),
                                      "n_all_kept": len(full), "best_all_kept": full[0] if full else None}
    return summary


def analyse(rosetta_in) -> dict:
    root = Path(rosetta_in)
    rows = list(csv.DictReader(open(root / "manifest.csv")))
    return {job: analyse_job(root / job, [r for r in rows if r["job"] == job]) for job in sorted({r["job"] for r in rows})}


def render_markdown(result: dict) -> str:
    L = ["# Step 4: do the docked poses keep the deposited ornithine's polar contacts?", "",
         "Generated by `python -m sidacore.contacts`; do not edit. Seed 1 only (the poses the Rosetta stage received). Polar contacts are heavy N/O pairs within %.1f A,"
         " scored per receptor residue; NADP contacts (residue 1493 in 4B63, 601 in 6X0J chain D) are listed but a pose is not penalised for losing them in the last two columns."
         " `Lys107 NZ` is the closest approach to either carboxylate oxygen (deposited value in the second column)." % CUTOFF, "",
         "| Job | Engine | Native contact residues | Top-1: RMSD | kept | lost | Lys107 NZ (A) | Closest-to-crystal pose: rank, RMSD | kept | Lys107 NZ | Poses keeping every protein contact | best of them: rank, RMSD |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for job, s in result.items():
        for engine, e in s["engines"].items():
            t, c, b = e["top1"], e["closest"], e["best_all_kept"]
            L.append("| %s | %s | %s (Lys107 %.2f) | %.2f | %d/%d | %s | %.2f | %d, %.2f | %d/%d | %.2f | %d of %d | %s |" % (
                job, engine, ", ".join(str(r[2]) for r in s["native"]), s["lys107_crystal"], t["rmsd"], t["kept"], len(s["native"]),
                ", ".join(map(str, t["lost"])) or "none", t["lys107"], c["rank"], c["rmsd"], c["kept"], len(s["native"]), c["lys107"],
                e["n_all_kept"], e["n_poses"], ("%d, %.2f" % (b["rank"], b["rmsd"])) if b else "-"))
    return "\n".join(L) + "\n"


def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--rosetta-in", default="rosetta_in")
    ap.add_argument("--out", default="reports/step4_contacts.md")
    a = ap.parse_args(argv)
    res = analyse(a.rosetta_in)
    Path(a.out).write_text(render_markdown(res))
    print("wrote", a.out)


if __name__ == "__main__":
    main()
