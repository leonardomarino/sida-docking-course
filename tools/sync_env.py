"""Release-time copy of the sida-docking env definition from protein-binders into env/.

The environment is defined ONCE, in protein-binders `environments/`. Students without access to
that repo get a generated, read-only copy of it, stamped with the source commit and hashes.
Never edit env/ by hand; re-run this at release time.

    python -m tools.sync_env --source /path/to/protein-binders [--dest env]

Refuses (SyncError, nothing written) if a source file is missing, untracked or has uncommitted
changes, so the copy always corresponds to a real commit.
"""
from __future__ import annotations

import argparse
import hashlib
import subprocess
import sys
from pathlib import Path

FILES = (
    "environments/sida-docking.yml",
    "environments/sida-docking.linux-64.explicit.txt",
    "environments/patches/sida_docking_caches.sh",
)


class SyncError(RuntimeError):
    """The source is not in a state that can be released. Never downgraded."""


def _git(repo: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True)


def _strip_prefix(yml: str) -> str:
    # A `prefix:` line makes `conda env create -f` try to build at the maintainer's path.
    return "".join(l for l in yml.splitlines(keepends=True) if not l.startswith("prefix:"))


def sync_env(source, dest) -> Path:
    source, dest = Path(source), Path(dest)
    if _git(source, "rev-parse", "--show-toplevel").returncode != 0:
        raise SyncError("%s is not a git checkout; cannot stamp the copy with a commit" % source)

    blobs = {}
    for rel in FILES:                                   # validate everything before writing anything
        path = source / rel
        if not path.is_file():
            raise SyncError("missing in source: %s" % rel)
        if _git(source, "ls-files", "--error-unmatch", "--", rel).returncode != 0:
            raise SyncError("not tracked by git in source: %s" % rel)
        if _git(source, "status", "--porcelain", "--", rel).stdout.strip():
            raise SyncError("uncommitted changes in source: %s (commit it first)" % rel)
        blobs[rel] = path.read_bytes()

    commit = _git(source, "rev-parse", "HEAD").stdout.strip()
    remote = _git(source, "remote", "get-url", "origin")
    origin = remote.stdout.strip() if remote.returncode == 0 else "(no origin remote)"

    dest.mkdir(parents=True, exist_ok=True)
    lines = ["GENERATED by tools/sync_env.py -- do not edit; re-run at release time.",
             "source repo: %s" % origin, "source commit: %s" % commit, "files (sha256 of the SOURCE bytes):"]
    for rel, data in blobs.items():
        out = data
        note = ""
        if rel.endswith(".yml"):
            out = _strip_prefix(data.decode()).encode()
            note = "  (copy has the prefix line removed)" if out != data else ""
        (dest / Path(rel).name).write_bytes(out)
        lines.append("  %s  %s%s" % (hashlib.sha256(data).hexdigest(), Path(rel).name, note))
    if any("prefix line removed" in l for l in lines):
        lines.append("note: prefix line removed from the .yml so conda builds at the user's own location")
    record = dest / "SOURCE.txt"
    record.write_text("\n".join(lines) + "\n")
    return record


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--source", required=True, help="protein-binders checkout")
    ap.add_argument("--dest", default="env")
    args = ap.parse_args(argv)
    try:
        print("wrote", sync_env(args.source, args.dest))
    except SyncError as e:
        print("sync_env: refused: %s" % e, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
